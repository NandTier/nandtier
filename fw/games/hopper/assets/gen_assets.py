"""Turn the platformer art and levels into data for the firmware.

    gen_assets.py <out.c> <out.h> <gfx_pack.bin>

Writes:
  out.c / out.h   CHR (256 tiles), palettes, block table, levels
  gfx_pack.bin    the same graphics as an SD card image for the game
                  (block 0: "NTGFX1" header, then 8 KiB CHR, then palettes);
                  write it with: make program SD_IMAGE=<gfx_pack.bin>

Tile numbers: 0x00-0x3F font (ASCII 0x20-0x5F), 0x40-0x7F background
blocks, 0x80-0xFF 16 x 16 sprites (tiles t, t+1, t+16, t+17).
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "hw", "video"))

import art          # noqa: E402
import levels       # noqa: E402
import gen_font     # noqa: E402  (the terminal font, reused for the status bar)

BLOCK_ORDER = ["sky", "ground_top", "ground", "brick", "question", "used", "stone",
               "pipe_top_l", "pipe_top_r", "pipe_l", "pipe_r", "coin",
               "cloud_l", "cloud_r", "bush_l", "bush_r", "pole", "pole_top"]
SOLID = {"ground_top", "ground", "brick", "question", "used", "stone",
         "pipe_top_l", "pipe_top_r", "pipe_l", "pipe_r"}
SPRITE_ORDER = ["hero_stand", "hero_walk1", "hero_walk2", "hero_jump", "hero_dead",
                "slime_1", "slime_2", "slime_flat", "coin_spin", "flag"]


def pixels(rows, key, w, h):
    assert len(rows) == h, (len(rows), rows)
    out = []
    for row in rows:
        assert len(row) == w, (len(row), row)
        out.append([key.index(ch) for ch in row])
    return out


def tile_word_rows(pix, x0, y0):
    """8 words for the 8 x 8 tile at (x0, y0): pixel k of a row in bits 4k+3..4k"""
    words = []
    for r in range(8):
        w = 0
        for k in range(8):
            w |= pix[y0 + r][x0 + k] << (4 * k)
        words.append(w)
    return tuple(words)


def main():
    out_c, out_h, out_bin = sys.argv[1:4]
    chr_tiles = [(0,) * 8] * 256

    # font: tile = ASCII - 0x20, white (colour 2) glyphs, one blank column left
    for code in range(0x20, 0x60):
        rows = gen_font.GLYPHS[chr(code)]
        pix = [[0] * 8 for _ in range(8)]
        for r in range(8):
            for c in range(5):
                if rows[r][c] == "#":
                    pix[r][c + 1] = 2
        chr_tiles[code - 0x20] = tile_word_rows(pix, 0, 0)

    # background blocks, cut into 8 x 8 tiles, shared where identical
    blocks = dict(art.BLOCKS)
    for names, rows in art.WIDE_BLOCKS.items():
        for i, name in enumerate(names):
            blocks[name] = [row[16 * i:16 * i + 16] for row in rows]
    blocks["sky"] = ["." * 16] * 16

    bg_tiles = {}
    next_tile = 0x40
    block_tiles = []
    for name in BLOCK_ORDER:
        pix = pixels(blocks[name], art.BG_KEY, 16, 16)
        ids = []
        for y0, x0 in ((0, 0), (0, 8), (8, 0), (8, 8)):
            t = tile_word_rows(pix, x0, y0)
            if t == (0,) * 8:
                ids.append(0)                   # font space: all sky
                continue
            if t not in bg_tiles:
                assert next_tile < 0x80, "too many background tiles"
                bg_tiles[t] = next_tile
                chr_tiles[next_tile] = t
                next_tile += 1
            ids.append(bg_tiles[t])
        block_tiles.append(ids)

    # sprites: sprite i at tile row 8 + 2 * (i // 8), column 2 * (i % 8)
    sprite_base = {}
    for i, name in enumerate(SPRITE_ORDER):
        base = (8 + 2 * (i // 8)) * 16 + 2 * (i % 8)
        pix = pixels(art.SPRITES[name], art.SPR_KEY, 16, 16)
        chr_tiles[base] = tile_word_rows(pix, 0, 0)
        chr_tiles[base + 1] = tile_word_rows(pix, 8, 0)
        chr_tiles[base + 16] = tile_word_rows(pix, 0, 8)
        chr_tiles[base + 17] = tile_word_rows(pix, 8, 8)
        sprite_base[name] = base

    chr_words = [w for t in chr_tiles for w in t]
    palette = art.BG_PALETTE + [0] * 48 + art.SPR_PALETTE + [0] * 48

    # --- C output ----------------------------------------------------------------
    with open(out_h, "w") as h:
        h.write("// Generated by fw/games/hopper/assets/gen_assets.py -- do not edit.\n")
        h.write("// SPDX-License-Identifier: Apache-2.0\n\n")
        h.write("#ifndef GAME_ASSETS_H\n#define GAME_ASSETS_H\n\n#include <stdint.h>\n\n")
        h.write("#define LEVEL_ROWS %d\n#define NUM_LEVELS %d\n\n" % (levels.ROWS, len(levels.LEVELS)))
        for i, name in enumerate(BLOCK_ORDER):
            h.write("#define BLK_%s %d\n" % (name.upper(), i))
        h.write("#define NUM_BLOCKS %d\n\n" % len(BLOCK_ORDER))
        for name in SPRITE_ORDER:
            h.write("#define SPR_%s 0x%02X\n" % (name.upper(), sprite_base[name]))
        h.write("\nextern const uint32_t game_chr[2048];\n")
        h.write("extern const uint16_t game_palette[128];\n")
        h.write("extern const uint16_t game_palette_night[16];\n")
        h.write("extern const uint8_t  block_tiles[NUM_BLOCKS][4];   // TL TR BL BR\n")
        h.write("extern const uint8_t  block_solid[NUM_BLOCKS];\n\n")
        h.write("struct level {\n\tconst char *name;\n\tuint8_t width, night, start, n_enemies;\n"
                "\tconst uint8_t *cells;      // [column][row]\n\tconst uint8_t *enemies;    // columns\n};\n\n")
        h.write("extern const struct level game_levels[NUM_LEVELS];\n\n#endif\n")

    with open(out_c, "w") as c:
        c.write("// Generated by fw/games/hopper/assets/gen_assets.py -- do not edit.\n")
        c.write("// SPDX-License-Identifier: Apache-2.0\n\n#include \"game_assets.h\"\n\n")
        c.write("const uint32_t game_chr[2048] = {\n")
        for i in range(0, 2048, 8):
            c.write("\t" + ", ".join("0x%08x" % w for w in chr_words[i:i + 8]) + ",\n")
        c.write("};\n\nconst uint16_t game_palette[128] = {\n")
        for i in range(0, 128, 16):
            c.write("\t" + ", ".join("0x%03x" % p for p in palette[i:i + 16]) + ",\n")
        c.write("};\n\nconst uint16_t game_palette_night[16] = {\n\t")
        c.write(", ".join("0x%03x" % p for p in art.BG_PALETTE_NIGHT) + "\n};\n\n")
        c.write("const uint8_t block_tiles[NUM_BLOCKS][4] = {\n")
        for name, ids in zip(BLOCK_ORDER, block_tiles):
            c.write("\t{0x%02x, 0x%02x, 0x%02x, 0x%02x},  // %s\n" % (*ids, name))
        c.write("};\n\nconst uint8_t block_solid[NUM_BLOCKS] = {\n\t")
        c.write(", ".join("1" if n in SOLID else "0" for n in BLOCK_ORDER) + "\n};\n\n")
        for i, lv in enumerate(levels.LEVELS):
            flat = [lv.cells[col][row] for col in range(lv.width) for row in range(levels.ROWS)]
            c.write("// %s\n// %s\n" % (lv.name, lv.ascii().replace("\n", "\n// ")))
            c.write("static const uint8_t level%d_cells[%d] = {\n" % (i, len(flat)))
            for j in range(0, len(flat), levels.ROWS):
                c.write("\t" + ",".join("%d" % v for v in flat[j:j + levels.ROWS]) + ",\n")
            c.write("};\nstatic const uint8_t level%d_enemies[] = {%s};\n\n"
                    % (i, ", ".join("%d" % e for e in lv.enemies)))
        c.write("const struct level game_levels[NUM_LEVELS] = {\n")
        for i, lv in enumerate(levels.LEVELS):
            c.write("\t{\"%s\", %d, %d, %d, %d, level%d_cells, level%d_enemies},\n"
                    % (lv.name, lv.width, int(lv.night), lv.start, len(lv.enemies), i, i))
        c.write("};\n")

    # --- SD graphics pack ------------------------------------------------------------
    with open(out_bin, "wb") as f:
        header = b"NTGFX1\0\0" + struct.pack("<II", 2048 * 4, 128 * 2)
        f.write(header + bytes(512 - len(header)))
        f.write(b"".join(struct.pack("<I", w) for w in chr_words))
        pal = b"".join(struct.pack("<H", p) for p in palette)
        f.write(pal + bytes(512 - len(pal)))

    print("assets: %d background tiles, %d sprites, levels %s"
          % (next_tile - 0x40, len(SPRITE_ORDER), ", ".join(lv.name for lv in levels.LEVELS)))


if __name__ == "__main__":
    main()
