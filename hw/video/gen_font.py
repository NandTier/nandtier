def glyph_bits(rows):
    """40-bit value: row r occupies bits [r*5+4 : r*5], leftmost column = bit 4."""
    value = 0
    for r, row in enumerate(rows):
        assert len(rows) == 8 and len(row) == 5, rows
        for c, ch in enumerate(row):
            if ch == '#':
                value |= 1 << (r * 5 + 4 - c)
    return value


def main():
    missing = [chr(c) for c in range(32, 127) if chr(c) not in GLYPHS]
    assert not missing, "glyphs missing: %r" % missing

    out = sys.stdout
    out.write("// Copyright 2026 Abdul Muheet Ghani\n")
    out.write("// SPDX-License-Identifier: Apache-2.0\n")
    out.write("//\n")
    out.write("// NandTier terminal font, generated by hw/video/gen_font.py -- edit the\n")
    out.write("// glyph drawings there and regenerate instead of editing this file.\n")
    out.write("//\n")
    out.write("// Combinational: lit = 1 when column col (0..4, left to right) of row\n")
    out.write("// row (0..7) of character code is lit. Codes outside 0x20..0x7E are blank.\n\n")
    out.write("`timescale 1 ns / 1 ps\n\n")
    out.write("module nt_font_rom (\n")
    out.write("\tinput  [6:0] code,\n")
    out.write("\tinput  [2:0] row,\n")
    out.write("\tinput  [2:0] col,\n")
    out.write("\toutput       lit\n")
    out.write(");\n")
    out.write("\treg [39:0] glyph;\n\n")
    out.write("\talways @* begin\n")
    out.write("\t\tcase (code)\n")
    for c in range(32, 127):
        ch = chr(c)
        shown = {'\\': 'backslash'}.get(ch, ch)
        out.write("\t\t\t7'h%02X: glyph = 40'h%010X;  // %s\n" % (c, glyph_bits(GLYPHS[ch]), shown))
    out.write("\t\t\tdefault: glyph = 40'h0;\n")
    out.write("\t\tendcase\n")
    out.write("\tend\n\n")
    out.write("\twire [5:0] bit_index = {3'd0, row} * 6'd5 + 6'd4 - {3'd0, col};\n\n")
    out.write("\tassign lit = col < 3'd5 && glyph[bit_index];\n\n")
    out.write("endmodule\n")


if __name__ == "__main__":
    main()
